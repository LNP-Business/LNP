"""Writes 002_q4_okrs.sql: loads the Q4 2026 OKRs (skl-os/seed.json, built from skl-os/kr_seed.js) into the live
database, renames the three objectives, and removes the demo key results, tasks, decisions and reviews.
Demo rows are deleted only when both their id and their content match the demo dataset (skl-os/dbseed), so
anything the team created is left untouched. Run after ./build.sh: python3 web/supabase/gen_002_q4_okrs.py"""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
seed = json.loads((ROOT / 'skl-os' / 'seed.json').read_text(encoding='utf-8'))
demo = ROOT / 'skl-os' / 'dbseed'
OBJECTIVES = [
    ('O1', 'Build world-class operations that iterate at PMF speed, without compromising student results'),
    ('O2', 'Build a world-class marketing engine that makes guru #1 the obvious choice in its market'),
    ('O3', 'Build a world-class sales system, ready to be replicated for every guru'),
]
def lit(s): return "'" + str(s).replace("'", "''") + "'"
def js(o): return lit(json.dumps(o, ensure_ascii=False)) + '::jsonb'
out = ['-- SKL OS · Q4 2026 OKRs. Generated by web/supabase/gen_002_q4_okrs.py, do not edit by hand.',
       '-- Run once in the Supabase SQL editor (project of skl-os.vercel.app). Safe to run again.', 'begin;', '',
       '-- 1. Remove the demo dataset (only rows whose id AND content still match the demo)']
for col, key in (('krs', 'name'), ('tasks', 'title'), ('decisions', 'title'), ('reviews', 'notes')):
    for f in sorted(demo.glob(col + '-*.json')):
        b = json.loads(f.read_text(encoding='utf-8'))
        out.append(f"delete from public.docs where col = {lit(col)} and id = {lit(b['id'])} and body->>{lit(key)} = {lit(b.get(key, ''))};")
out += ['', '-- 2. The three Q4 objectives']
cfg = {'id': 'objectives', 'list': [{'id': i, 'name': n, 'quarter': 'Q4 2026'} for i, n in OBJECTIVES]}
out.append(f"insert into public.docs (col, id, body) values ('config', 'objectives', {js(cfg)})\n  on conflict (col, id) do update set body = excluded.body;")
out += ['', '-- 3. The nine Q4 key results and the first to-dos from the KR memos']
for col in ('krs', 'tasks'):
    for d in seed[col]:
        out.append(f"insert into public.docs (col, id, body) values ({lit(col)}, {lit(d['id'])}, {js(d)})\n  on conflict (col, id) do update set body = excluded.body;")
out += ['', '-- 4. The KR memos, in Knowledge System › Library (kept if the team already edited them)']
for d in seed.get('deliverables', []):
    out.append(f"insert into public.docs (col, id, body) values ('deliverables', {lit(d['id'])}, {js(d)})\n  on conflict (col, id) do nothing;")
out += ['', 'commit;', '']
p = ROOT / 'web' / 'supabase' / '002_q4_okrs.sql'
p.write_text('\n'.join(out), encoding='utf-8')
print(p, len(seed['krs']), 'krs', len(seed['tasks']), 'tasks', len(seed.get('deliverables', [])), 'memos')
